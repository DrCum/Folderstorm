#!/usr/bin/env python3
"""Optional asset regeneration; ordinary Windows builds use the checked-in header.

Requires Python Playwright and Chromium. Only local, validated SVGs are rendered;
no network, font dependency or SVG parser is required by the installed host.
"""
import json
import os
from pathlib import Path
import xml.etree.ElementTree as ET
from playwright.sync_api import sync_playwright

ROOT = Path(__file__).resolve().parent
NAMES = ['cctv', 'settings', 'messages-square', 'user-plus', 'external-link',
         'arrow-down-left', 'chevron-up', 'chevron-down', 'pin', 'bell',
         'layout-dashboard', 'rotate-cw', 'mic', 'volume-x', 'info', 'ellipsis',
         'palette', 'mouse-pointer-click']
SIZES = [16, 20, 24, 25, 30, 32, 35, 40, 45, 48, 50, 56, 60, 64, 68, 80, 90, 96]

def pack(values):
    result = []
    for value in values:
        if result and result[-1] == value and result[-2] < 255:
            result[-2] += 1
        else:
            result.extend([1, value])
    return result

sources = {}
for name in NAMES:
    text = (ROOT / 'lucide' / (name + '.svg')).read_text()
    tree = ET.fromstring(text)
    for element in tree.iter():
        assert element.tag.rsplit('}', 1)[-1] in {'svg', 'path', 'line', 'rect', 'circle', 'ellipse', 'polyline', 'polygon'}
        assert not any(key.lower().startswith('on') or 'href' in key.lower() for key in element.attrib)
    sources[name] = text.replace('stroke-width="2"', 'stroke-width="1.75"')

header = ['// Generated by icons/generate_lucide.py. Lucide license: icons/lucide/LICENSE.',
          '#ifndef FS_HOST_LUCIDE_DATA_H', '#define FS_HOST_LUCIDE_DATA_H',
          '#include <cstddef>', '#include <cstdint>', 'namespace fs_host_ui {',
          'enum class Icon : unsigned int { None, ' + ', '.join(''.join(word.title() for word in name.split('-')) for name in NAMES) + ' };',
          'struct IconMask { Icon icon; int size; const std::uint8_t* runs; std::size_t length; };']
records = []
with sync_playwright() as p:
    browser = p.chromium.launch(executable_path=os.environ.get('FOLDERSTORM_ICON_BROWSER','/usr/bin/chromium'), args=['--no-sandbox'])
    page = browser.new_page()
    page.set_content('<canvas id="canvas"></canvas>')
    for name, svg in sources.items():
        enum = ''.join(word.title() for word in name.split('-'))
        for size in SIZES:
            values = page.evaluate('''async ({svg,size}) => {
              const image = new Image();
              image.src = 'data:image/svg+xml;base64,' + btoa(svg);
              await image.decode();
              const canvas = document.getElementById('canvas'); canvas.width = canvas.height = size;
              const context = canvas.getContext('2d'); context.drawImage(image,0,0,size,size);
              const rgba = context.getImageData(0,0,size,size).data;
              return Array.from({length:size*size}, (_,i)=>rgba[i*4+3]);
            }''', dict(svg=svg, size=size))
            runs = pack(values)
            ident = 'mask' + enum + str(size)
            header.append('inline constexpr std::uint8_t ' + ident + '[] = {')
            header.extend('    ' + ','.join(str(n) for n in runs[at:at+40]) + ',' for at in range(0, len(runs), 40))
            header.append('};')
            records.append('{Icon::' + enum + ',' + str(size) + ',' + ident + ',sizeof(' + ident + ')}')
    browser.close()
header.append('inline constexpr IconMask iconMasks[] = {\n    ' + ',\n    '.join(records) + '\n};')
license_text = (ROOT / 'lucide' / 'LICENSE').read_text()
assert ')FSICONLICENSE"' not in license_text
header.append('inline constexpr char lucideLicense[] = R"FSICONLICENSE(' + license_text + ')FSICONLICENSE";')
header.extend(['}', '#endif', ''])
target = ROOT.parent / 'lucide_data.h'
target.write_text('\n'.join(header))
print(json.dumps({'icons': len(NAMES), 'masks': len(records), 'bytes': target.stat().st_size}))
